#!/bin/sh
# Runs once, on an empty data directory, before the final PostgreSQL start.
# Generates a self-signed certificate for encryption in transit inside the
# internal Compose network. Clients use sslmode=require (not verify-full)
# because the certificate is generated per database volume.
set -eu

CERT_DIR=/var/lib/postgresql/data/tls
mkdir -p "$CERT_DIR"

if [ ! -f "$CERT_DIR/server.crt" ] || [ ! -f "$CERT_DIR/server.key" ]; then
  openssl req -x509 -newkey rsa:2048 -nodes -days 3650 \
    -keyout "$CERT_DIR/server.key" \
    -out "$CERT_DIR/server.crt" \
    -subj '/CN=db.jsbh.internal' 2>/dev/null
fi

chmod 600 "$CERT_DIR/server.key"
chmod 644 "$CERT_DIR/server.crt"
chown -R postgres:postgres "$CERT_DIR"

{
  echo ''
  echo '# Generated by deploy/db-init/01-tls.sh'
  echo "ssl = on"
  echo "ssl_cert_file = 'tls/server.crt'"
  echo "ssl_key_file = 'tls/server.key'"
} >> /var/lib/postgresql/data/postgresql.conf
